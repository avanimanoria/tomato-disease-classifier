function R = pipelineRegistry()
%PIPELINEREGISTRY Every selectable method per pipeline stage, with availability.
%
%   R = pipelineRegistry() returns a struct of tables (one per stage) with columns
%   id, label, available, implementation, status, note. Only available methods can be run;
%   unavailable ones are listed so the UI can show them as UNAVAILABLE (fail closed).
%   ALGORITHM_REGISTRY.md documents the same list.
    [cnnOk, cnnWhy] = cnnAvailability();
    R.perception = mk({ ...
        'parametric', 'Parametric detector (baseline)', true, 'detectPlants.m', 'synthetic', 'fixed P(detect)=0.95, P(FP)=0.03 per observed plant'; ...
        'cnn', 'Teammate CNN', cnnOk, 'perceptionCNNAdapter.m', 'blocked', cnnWhy});
    R.localization = mk({ ...
        'groundTruthOracle', 'Ground truth (ORACLE upper bound)', true, 'getEstimatedState.m', 'oracle', 'controller receives the true position'; ...
        'errorModel', 'Error model (proxy)', true, 'stepVehicleAdvanced.m', 'proxy', 'truth + modelled random walk / scale error / resets'; ...
        'imuDeadReckoning', 'IMU dead reckoning (weak baseline)', true, 'stepVehicleAdvanced.m', 'synthetic sensors', 'double-integrated accelerometer, no fixes'; ...
        'flowOdometry', 'Optical-flow odometry', true, 'stepVehicleAdvanced.m', 'synthetic sensors', 'integrated flow velocity, no fixes'; ...
        'kalman', 'Linear KF (flow + periodic fixes)', true, 'stepVehicleAdvanced.m', 'synthetic sensors', 'position-only KF; fix source not modelled physically'; ...
        'sensorFusion', 'EKF sensor fusion (IMU + flow + LiDAR landmarks)', exist('sensorFusionStep', 'file') == 2, ...
            'sensorFusionStep.m', 'synthetic sensors', 'planar EKF; landmarks = field corner posts'});
    R.coverage = mk({ ...
        'boustrophedon', 'Boustrophedon along crop rows (original)', true, 'generateIrregularField.m', 'implemented', ''; ...
        'polygonDecomposition', 'Polygon cell decomposition (concave / obstacles)', exist('planCoverageDecomposition', 'file') == 2, ...
            'planCoverageDecomposition.m', 'implemented', ...
            'obstacle-aware Pass 1 + Pass-2 legs (freeSpacePath); identical to boustrophedon on convex fields without obstacles'});
    R.controller = mk({ ...
        'openLoop', 'Open loop (PID off)', true, 'pidCrossTrackController.m', 'implemented', 'feed-forward only'; ...
        'pid', 'PID cross-track', true, 'pidCrossTrackController.m', 'implemented', ''; ...
        'purePursuit', 'Pure pursuit', true, 'purePursuitController.m', 'implemented', 'gains not tuned'});
    R.routing = mk({ ...
        'fixedOrder', 'Fixed (detection) order', true, 'runTreatmentPass.m', 'implemented', ''; ...
        'nearestNeighbour', 'Nearest neighbour', true, 'planTreatmentRoute.m', 'implemented', ''; ...
        'nearestNeighbour2opt', 'NN + 2-opt', true, 'planRouteAdvanced.m', 'implemented', ''; ...
        'nearestNeighbourOrOpt', 'NN + 2-opt + Or-opt', true, 'planRouteAdvanced.m', 'implemented', ''; ...
        'cheapestInsertion', 'Cheapest insertion', true, 'planRouteAdvanced.m', 'implemented', ''; ...
        'antColony', 'Ant colony (+2-opt)', true, 'planRouteAdvanced.m', 'implemented', 'seeded'; ...
        'stage7Return', 'Stage-7 return to path (original)', true, 'runTreatmentPass.m', 'implemented', 'flies at 0.6x speed'; ...
        'riskAware', 'Risk / energy-aware', false, '-', 'not implemented', 'planned (manual M6)'});
    R.sprayCompensation = mk({ ...
        'none', 'No compensation', true, 'sprayContext.m', 'implemented', ''; ...
        'wind', 'Wind (upwind offset)', true, 'sprayContext.m / advSprayPlan.m', 'implemented', 'uses mean wind x windEstimateScale'; ...
        'windLag', 'Wind + valve-lag compensation', true, 'advActuatedDeposition.m', 'implemented', 'needs a valve delay to matter'; ...
        'uncertaintyAware', 'Uncertainty-aware release', false, '-', 'not implemented', ''});
    R.kernel = mk({ ...
        'gaussian', 'Circular Gaussian (original)', true, 'depositSpray.m', 'UNCALIBRATED', ''; ...
        'windStretched', 'Wind-stretched ellipse', true, 'advDepositKernel.m', 'UNCALIBRATED', ''; ...
        'calibrated', 'Calibrated kernel', false, '-', 'blocked', 'no extractable deposition dataset supplied'});
    R.mode = mk({ ...
        'manual', 'Manual combination', true, 'runPipeline.m', 'implemented', ''; ...
        'bestFixed', 'Best fixed (saved Experiment F)', true, 'results/benchmark/benchmark.mat', 'saved model', 'controller + spray stages only'; ...
        'scenarioSelector', 'Scenario selector (saved Experiment F)', true, 'results/benchmark/benchmark.mat', 'saved model', 'controller + spray stages only; trained scenarios only'; ...
        'oracle', 'Oracle (research only, hindsight)', true, 'runPipeline.m', 'non-deployable', 'runs all 6 controller x spray choices and keeps the best'});
end

function T = mk(c)
    T = cell2table(c, 'VariableNames', {'id', 'label', 'available', 'implementation', 'status', 'note'});
    T.available = logical(T.available);
end
